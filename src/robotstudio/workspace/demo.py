"""A small starter document that demonstrates the canvas model."""

from __future__ import annotations

from robotstudio.model.canvas import (
    Argument,
    CallStep,
    CanvasDocument,
    ForStep,
    IfStep,
    KeywordDefinition,
    KeywordRef,
    LibraryImport,
    SuiteSettings,
    TestCase,
    TryStep,
    Variable,
)


def _call(name: str, *values: str, assign: list[str] | None = None) -> CallStep:
    return CallStep(
        keyword=KeywordRef(name=name),
        args=[Argument(value=value) for value in values],
        assign=assign or [],
    )


def demo_document() -> CanvasDocument:
    """Build a small, hardware-free suite used by ``robotstudio init``."""
    settings = SuiteSettings(
        documentation="Starter suite generated by Robotstudio.",
        libraries=[LibraryImport(name="Collections")],
        suite_setup=_call("Log", "Robotstudio demo started"),
        test_teardown=_call("Log", "Test finished"),
        variables=[Variable(name="GREETING", value="Hello from Robotstudio")],
    )
    tests = [
        TestCase(
            name="Log A Greeting",
            documentation="A minimal smoke test written with the canvas model.",
            tags=["demo", "smoke"],
            steps=[
                _call("Log", "${GREETING}"),
                _call(
                    "Should Be Equal",
                    "${GREETING}",
                    "Hello from Robotstudio",
                ),
            ],
        ),
        TestCase(
            name="Build A List",
            documentation="Create a list and iterate over it.",
            tags=["demo"],
            steps=[
                _call("Create List", "alpha", "beta", assign=["items"]),
                ForStep(
                    variables=["item"],
                    values=["@{items}"],
                    steps=[_call("Log", "${item}")],
                ),
                _call("Length Should Be", "${items}", "2"),
            ],
        ),
        TestCase(
            name="Conditional Check",
            documentation="Branch on a value and use a user keyword.",
            tags=["demo"],
            steps=[
                _call("Set Variable", "7", assign=["value"]),
                IfStep(
                    condition="${value} > 5",
                    steps=[_call("Log Twice", "Value is large")],
                    else_steps=[_call("Log Twice", "Value is small")],
                ),
                _call("Should Be True", "${value} == 7"),
            ],
        ),
    ]
    keywords = [
        KeywordDefinition(
            name="Log Twice",
            arguments=["${message}"],
            documentation="Log the same message twice.",
            steps=[_call("Log", "${message}"), _call("Log", "${message}")],
        ),
        KeywordDefinition(
            name="Count To",
            arguments=["${limit}"],
            documentation="Count upwards, then prove the loop ran.",
            steps=[
                _call("Set Variable", "0", assign=["count"]),
                ForStep(
                    variables=["index"],
                    values=["1", "${limit}"],
                    flavor="in_range",
                    steps=[
                        _call(
                            "Evaluate",
                            "${count} + 1",
                            assign=["count"],
                        )
                    ],
                ),
                TryStep(
                    steps=[
                        _call(
                            "Should Be Equal As Integers",
                            "${count}",
                            "${limit}",
                        )
                    ]
                ),
            ],
        ),
    ]
    return CanvasDocument(
        name="Robotstudio Demo",
        settings=settings,
        tests=tests,
        keywords=keywords,
    )
